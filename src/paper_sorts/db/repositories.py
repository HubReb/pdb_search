class AuthorRepository:
    """Repository for authors_id and authors_papers tables."""

    def __init__(self, session: Session) -> None:
        """Initialise with an active SQLAlchemy session.

        :param session: active database session
        :type session: Session
        """
        self._session = session

    def get_or_create(self, author_name: str) -> Author:
        """Return an existing Author record or create a new one.

        :param author_name: author name in "Last, First" format
        :type author_name: str
        :return: Author ORM object
        :rtype: Author
        """
        stmt = select(Author).where(Author.author == author_name)
        existing = self._session.execute(stmt).scalar_one_or_none()
        if existing is not None:
            return existing
        author = Author(author=author_name)
        self._session.add(author)
        self._session.flush()
        return author

    def link_author_to_paper(self, author_id: int, paper_id: int) -> None:
        """Create an authors_papers link between an author and a paper.

        :param author_id: id from authors_id table
        :type author_id: int
        :param paper_id: id from papers table
        :type paper_id: int
        """
        link = AuthorPaper(author_id=author_id, paper_id=paper_id)
        self._session.add(link)
        self._session.flush()

    def get_authors_for_paper(self, paper_id: int) -> list[str]:
        """Return a list of author names for the given paper.

        :param paper_id: papers.id to look up authors for
        :type paper_id: int
        :return: list of author names in "Last, First" format
        :rtype: list[str]
        """
        stmt = (
            select(Author.author)
            .join(AuthorPaper, AuthorPaper.author_id == Author.id)
            .where(AuthorPaper.paper_id == paper_id)
        )
        rows = self._session.execute(stmt).scalars().all()
        return list(rows)

    def get_by_name(self, author_name: str) -> Author | None:
        """Fetch an author by exact name.

        :param author_name: author name to look up
        :type author_name: str
        :return: Author ORM object or None
        :rtype: Author | None
        """
        stmt = select(Author).where(Author.author == author_name)
        return self._session.execute(stmt).scalar_one_or_none()

    def unlink_author_from_paper(self, author_id: int, paper_id: int) -> None:
        """Remove an author-paper link from authors_papers.

        :param author_id: authors_id.id
        :type author_id: int
        :param paper_id: papers.id
        :type paper_id: int
        """
        stmt = select(AuthorPaper).where(
            AuthorPaper.author_id == author_id,
            AuthorPaper.paper_id == paper_id,
        )
        link = self._session.execute(stmt).scalar_one_or_none()
        if link is not None:
            self._session.delete(link)
            self._session.flush()

    def author_has_other_papers(self, author_id: int, excluding_paper_id: int) -> bool:
        """Check whether an author has papers other than the specified one.

        :param author_id: authors_id.id
        :type author_id: int
        :param excluding_paper_id: paper_id to exclude from the check
        :type excluding_paper_id: int
        :return: True if the author is linked to at least one other paper
        :rtype: bool
        """
        stmt = select(AuthorPaper).where(
            AuthorPaper.author_id == author_id,
            AuthorPaper.paper_id != excluding_paper_id,
        )
        return self._session.execute(stmt).scalar_one_or_none() is not None

    def delete_author(self, author_id: int) -> None:
        """Delete an author record from authors_id.

        :param author_id: authors_id.id to delete
        :type author_id: int
        """
        stmt = select(Author).where(Author.id == author_id)
        author = self._session.execute(stmt).scalar_one_or_none()
        if author is not None:
            self._session.delete(author)
            self._session.flush()

    def update_author_name(self, author_id: int, new_name: str) -> None:
        """Update an author's name in the authors_id table.

        :param author_id: authors_id.id to update
        :type author_id: int
        :param new_name: new author name in "Last, First" format
        :type new_name: str
        :raises ValueError: if the author_id does not exist
        """
        stmt = select(Author).where(Author.id == author_id)
        author = self._session.execute(stmt).scalar_one_or_none()
        if author is None:
            raise ValueError(f"Author with id {author_id} not found")
        author.author = new_name
        self._session.flush()


