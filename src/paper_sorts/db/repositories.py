"""Repository classes and pydantic DTOs for paper_sorts database operations.

This module is the only place outside of models.py that may import SQLAlchemy.
Services depend on the DTO types defined here, never on ORM model types.

DTOs:
- PaperCreate: input for adding a new paper
- PaperSummary: output from search operations

Repositories:
- BibRepository: CRUD for the bib table
- PaperRepository: CRUD and search for the papers table
- AuthorRepository: CRUD for authors_id and authors_papers tables
"""

from __future__ import annotations

import logging
from typing import Sequence

from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.orm import Session

from paper_sorts.db.models import Author, AuthorPaper, Bib, Paper

logger = logging.getLogger("paper_sorts.db.repositories")


# ---------------------------------------------------------------------------
# Pydantic DTOs
# ---------------------------------------------------------------------------


class PaperCreate(BaseModel):
    """Input DTO for creating a new paper entry.

    :param title: title of the publication
    :param contents: one-sentence summary of the paper
    :param bibtex_id: unique BibTeX citation key
    :param bibtex: full BibTeX source string
    :param authors: list of author names in "Last, First" format
    """

    title: str
    contents: str
    bibtex_id: str
    bibtex: str
    authors: list[str]


class PaperSummary(BaseModel):
    """Output DTO from search operations.

    :param paper_id: internal papers.id
    :param title: title of the publication
    :param contents: one-sentence summary
    :param bibtex_id: unique BibTeX citation key
    :param bibtex: full BibTeX source string
    :param authors: list of author names in "Last, First" format
    """

    paper_id: int
    title: str
    contents: str
    bibtex_id: str
    bibtex: str
    authors: list[str]


# ---------------------------------------------------------------------------
# Repository: Bib
# ---------------------------------------------------------------------------


class BibRepository:
    """Repository for the bib table (BibTeX entries).

    All SQL is generated by SQLAlchemy ORM/Core — no raw SQL strings.
    """

    def __init__(self, session: Session) -> None:
        """Initialise with an active SQLAlchemy session.

        :param session: active database session
        :type session: Session
        """
        self._session = session

    def get_by_id(self, bibtex_id: str) -> Bib | None:
        """Fetch a BibTeX entry by its primary key.

        :param bibtex_id: BibTeX citation key to look up
        :type bibtex_id: str
        :return: Bib ORM object, or None if not found
        :rtype: Bib | None
        """
        return self._session.get(Bib, bibtex_id)

    def exists(self, bibtex_id: str) -> bool:
        """Check whether a bibtex_id exists in the bib table.

        :param bibtex_id: BibTeX citation key to check
        :type bibtex_id: str
        :return: True if the key exists
        :rtype: bool
        """
        return self._session.get(Bib, bibtex_id) is not None

    def create(self, bibtex_id: str, bibtex: str) -> Bib:
        """Insert a new BibTeX entry into the bib table.

        :param bibtex_id: unique BibTeX citation key
        :type bibtex_id: str
        :param bibtex: full BibTeX source string
        :type bibtex: str
        :return: the newly created Bib ORM object
        :rtype: Bib
        """
        entry = Bib(bibtex_id=bibtex_id, bibtex=bibtex)
        self._session.add(entry)
        self._session.flush()
        return entry

    def update(self, bibtex_id: str, new_bibtex: str) -> Bib:
        """Update the bibtex string for an existing entry.

        :param bibtex_id: BibTeX citation key identifying the entry
        :type bibtex_id: str
        :param new_bibtex: new full BibTeX source string
        :type new_bibtex: str
        :return: updated Bib ORM object
        :rtype: Bib
        :raises ValueError: if bibtex_id does not exist in the table
        """
        entry = self.get_by_id(bibtex_id)
        if entry is None:
            raise ValueError(f"BibTeX entry '{bibtex_id}' not found in bib table")
        entry.bibtex = new_bibtex
        self._session.flush()
        return entry

    def delete(self, bibtex_id: str) -> None:
        """Delete a BibTeX entry from the bib table.

        :param bibtex_id: BibTeX citation key to delete
        :type bibtex_id: str
        :raises ValueError: if bibtex_id does not exist
        """
        entry = self.get_by_id(bibtex_id)
        if entry is None:
            raise ValueError(f"BibTeX entry '{bibtex_id}' not found")
        self._session.delete(entry)
        self._session.flush()


