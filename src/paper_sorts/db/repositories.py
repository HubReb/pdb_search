class PaperRepository:
    """Repository for the papers table with search operations."""

    def __init__(self, session: Session) -> None:
        """Initialise with an active SQLAlchemy session.

        :param session: active database session
        :type session: Session
        """
        self._session = session
        self._bib_repo = BibRepository(session)
        self._author_repo = AuthorRepository(session)

    def _build_summary(self, paper: Paper) -> PaperSummary:
        """Build a PaperSummary DTO from an ORM Paper object.

        :param paper: ORM Paper object
        :type paper: Paper
        :return: PaperSummary DTO with all fields populated
        :rtype: PaperSummary
        """
        bib = self._bib_repo.get_by_id(paper.bibtex_id)
        bibtex = bib.bibtex if bib else ""
        authors = self._author_repo.get_authors_for_paper(paper.id)
        return PaperSummary(
            paper_id=paper.id,
            title=paper.title,
            contents=paper.contents,
            bibtex_id=paper.bibtex_id,
            bibtex=bibtex,
            authors=authors,
        )

    def search_by_title(self, title: str) -> list[PaperSummary]:
        """Search for papers by exact title match.

        :param title: paper title to search for (exact match)
        :type title: str
        :return: list of PaperSummary DTOs for matching papers
        :rtype: list[PaperSummary]
        """
        stmt = select(Paper).where(Paper.title == title)
        papers: Sequence[Paper] = self._session.execute(stmt).scalars().all()
        return [self._build_summary(p) for p in papers]

    def search_by_author(self, author_name: str) -> list[PaperSummary]:
        """Search for papers by exact author name.

        :param author_name: author name in "Last, First" format (exact match)
        :type author_name: str
        :return: list of PaperSummary DTOs for papers by this author
        :rtype: list[PaperSummary]
        """
        stmt = (
            select(Paper)
            .join(AuthorPaper, AuthorPaper.paper_id == Paper.id)
            .join(Author, Author.id == AuthorPaper.author_id)
            .where(Author.author == author_name)
        )
        papers: Sequence[Paper] = self._session.execute(stmt).scalars().all()
        return [self._build_summary(p) for p in papers]

    def get_by_bibtex_id(self, bibtex_id: str) -> PaperSummary | None:
        """Fetch a paper by its BibTeX citation key.

        :param bibtex_id: BibTeX citation key
        :type bibtex_id: str
        :return: PaperSummary DTO or None if not found
        :rtype: PaperSummary | None
        """
        stmt = select(Paper).where(Paper.bibtex_id == bibtex_id)
        paper = self._session.execute(stmt).scalar_one_or_none()
        if paper is None:
            return None
        return self._build_summary(paper)

    def get_by_id(self, paper_id: int) -> PaperSummary | None:
        """Fetch a paper by its internal integer id.

        :param paper_id: papers.id value
        :type paper_id: int
        :return: PaperSummary DTO or None if not found
        :rtype: PaperSummary | None
        """
        paper = self._session.get(Paper, paper_id)
        if paper is None:
            return None
        return self._build_summary(paper)

    def create(self, paper_data: PaperCreate) -> PaperSummary:
        """Insert a new paper (bib + paper + author links) in one transaction.

        All operations use the shared session; the caller is responsible for
        committing via with_session context manager.

        :param paper_data: DTO with all required paper fields
        :type paper_data: PaperCreate
        :return: PaperSummary DTO for the newly created paper
        :rtype: PaperSummary
        :raises ValueError: if bibtex_id already exists in the bib table
        """
        if self._bib_repo.exists(paper_data.bibtex_id):
            raise ValueError(
                f"BibTeX key '{paper_data.bibtex_id}' already exists. "
                "Use a unique key or update the existing entry."
            )

        # Insert bib entry first (papers has FK → bib)
        self._bib_repo.create(paper_data.bibtex_id, paper_data.bibtex)

        # Insert paper record
        paper = Paper(
            title=paper_data.title,
            contents=paper_data.contents,
            bibtex_id=paper_data.bibtex_id,
        )
        self._session.add(paper)
        self._session.flush()  # flush to get paper.id

        # Link authors
        for author_name in paper_data.authors:
            author = self._author_repo.get_or_create(author_name)
            self._author_repo.link_author_to_paper(author.id, paper.id)

        return self._build_summary(paper)

    def update_title(self, paper_id: int, new_title: str) -> None:
        """Update the title of a paper.

        :param paper_id: papers.id to update
        :type paper_id: int
        :param new_title: new title string
        :type new_title: str
        :raises ValueError: if paper_id does not exist
        """
        paper = self._session.get(Paper, paper_id)
        if paper is None:
            raise ValueError(f"Paper with id {paper_id} not found")
        paper.title = new_title
        self._session.flush()

    def update_contents(self, paper_id: int, new_contents: str) -> None:
        """Update the summary/contents of a paper.

        :param paper_id: papers.id to update
        :type paper_id: int
        :param new_contents: new summary string
        :type new_contents: str
        :raises ValueError: if paper_id does not exist
        """
        paper = self._session.get(Paper, paper_id)
        if paper is None:
            raise ValueError(f"Paper with id {paper_id} not found")
        paper.contents = new_contents
        self._session.flush()

    def delete(self, paper_id: int) -> None:
        """Delete a paper and its bib entry; clean up orphaned authors.

        Deletes in this order to respect FK:
        1. Unlink all authors from this paper (authors_papers rows)
        2. Delete orphaned authors (authors with no remaining papers)
        3. Delete the paper row
        4. Delete the bib row

        :param paper_id: papers.id to delete
        :type paper_id: int
        :raises ValueError: if paper does not exist
        """
        paper = self._session.get(Paper, paper_id)
        if paper is None:
            raise ValueError(f"Paper with id {paper_id} not found")

        bibtex_id = paper.bibtex_id

        # Find all author links for this paper
        stmt = select(AuthorPaper).where(AuthorPaper.paper_id == paper_id)
        links = self._session.execute(stmt).scalars().all()

        for link in links:
            author_id = link.author_id
            self._session.delete(link)
            self._session.flush()
            # Delete author if they have no other papers
            if not self._author_repo.author_has_other_papers(author_id, paper_id):
                self._author_repo.delete_author(author_id)

        # Delete the paper row
        self._session.delete(paper)
        self._session.flush()

        # Delete the bib row
        self._bib_repo.delete(bibtex_id)
